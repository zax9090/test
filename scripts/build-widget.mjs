/**
 * Bundle the widget into a single self-contained HTML document.
 *
 * The iframe runs under a CSP with `default-src 'none'` — no CDN, no external
 * stylesheet, no font fetch, no transitive module resolution. Anything not
 * inlined here simply does not load, and the failure mode is a blank rectangle
 * whose error only appears in the iframe's own console. So everything goes in:
 * React, the ext-apps runtime, our code, the CSS.
 *
 * The ext-apps `*-with-deps` entry points are self-contained browser builds, so
 * esbuild can bundle them directly. That avoids the export-rewriting trick the
 * skill documents for un-bundled widgets — there is no regex over a minified
 * bundle here, and nothing to go wrong with `$` sequences in a replacement.
 *
 * Output is a TS module exporting the HTML as a JSON-escaped string literal,
 * which the Worker imports. Escaping via JSON.stringify keeps backticks and
 * `${` in the bundle from breaking the emitted file.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const outDir = resolve(root, "src/generated");

const result = await build({
  entryPoints: [resolve(root, "src/widget/index.tsx")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2022"],
  jsx: "automatic",
  // Preact through the compat layer. React's own build is ~170KB of the bundle
  // and this widget uses nothing outside the common API; the host fetches this
  // document as a resource, so the weight is on every render.
  alias: {
    react: "preact/compat",
    "react-dom/client": "preact/compat/client",
    "react-dom": "preact/compat",
    "react/jsx-runtime": "preact/compat/jsx-runtime",
  },
  minify: true,
  write: false,
  legalComments: "none",
  // Production React: the dev build ships warnings and slower paths we have no
  // way to see inside the sandbox anyway.
  define: { "process.env.NODE_ENV": '"production"' },
});

const js = result.outputFiles[0].text;
const css = readFileSync(resolve(root, "src/widget/styles.css"), "utf8");

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
/* The host owns the page background; the widget only paints its own text. */
html, body { margin: 0; padding: 0; background: transparent; color-scheme: light dark; }
${css}
</style>
</head>
<body>
<div id="root"></div>
<script>${js}</script>
</body>
</html>
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(
  resolve(outDir, "widget-html.ts"),
  `// Generated by scripts/build-widget.mjs — do not edit.\n` +
    `export default ${JSON.stringify(html)};\n`,
  "utf8",
);

const kb = (n) => `${(n / 1024).toFixed(0)}KB`;
console.log(`widget: ${kb(js.length)} js + ${kb(css.length)} css -> ${kb(html.length)} html`);
